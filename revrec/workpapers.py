"""Audit workpapers (SPEC 6 item 9; build step 9, MVP pieces).

- output/workpapers/controls_matrix.md: each SPEC 7 control, what it proves, how the model
  tests it, evidence, owner and reviewer, and its result each month
- output/workpapers/sample_tieouts.md: five invoices traced from usage rows -> billing
  ledger -> invoice -> GL -> cash, through the ledger_id trail

The revenue lead sheet and the tickmarked contract liability rollforward come after
submission (SPEC 8).
"""

from dataclasses import dataclass
from decimal import Decimal
from pathlib import Path

from revrec.billing import MONTH_NAMES

ZERO = Decimal("0.00")
MONTHS = ["2026-01", "2026-02", "2026-03"]
BILLING = "Billing engineering"
REVENUE = "Finance Manager, Revenue Accounting"
GL = "GL accountant"


# --- Controls matrix ----------------------------------------------------------------------------------

@dataclass
class Control:
    name: str
    proves: str     # SPEC 7
    test: str       # how the model tests it
    evidence: str
    owner: str


CONTROLS = [
    Control("Completeness", "Raw usage units received = free-tier + tiered + duplicate + late units. Nothing disappears silently.",
            "Bridge A: units received by customer, product, and month, less each category, leaves zero.",
            "reconciliation.md, bridge A", BILLING),
    Control("Cutoff", "Every row is assigned to a period by received_ts (UTC). Usage processed after the cutoff is covered by the lag estimate, and estimate vs actual is tracked each month.",
            "Lag estimate equals the lag rate x processed usage revenue; late usage appears in the lag report with estimate vs actual.",
            "lag_report.csv; close_checklist.md, BD3", REVENUE),
    Control("Close threshold", "Unusual items are measured in aggregate against the threshold, and every passed item is logged with a running total.",
            "Each month's unusual items, in aggregate, are below the threshold, and each is in the log.",
            "passed_adjustments_log.csv", REVENUE),
    Control("Pricing accuracy", "Invoice totals are independently recomputed from the rate card and agree.",
            "Every tiered invoice line recomputes as units x unit price; invoices are issued on business day 2.",
            "invoices.csv; close_checklist.md, BD2", BILLING),
    Control("Integration", "Every billing ledger row is mapped to the GL. GL account totals tie to the billing ledger.",
            "Every ledger row is posted, memo-only, or an exception; GL totals by account are recomputed from the ledger; a rerun is identical.",
            "gl_export.csv; exceptions.csv", REVENUE),
    Control("Balance", "Every journal entry balances, and the trial balance is in balance.",
            "Debits equal credits in every daily journal entry and across the trial balance.",
            "gl_export.csv", GL),
    Control("Rollforwards", "Each rollforward ties to the GL. Contract liability = remaining credit x 0.80.",
            "Every rollforward's closing balance equals its GL account at month end, with zero difference.",
            "rollforwards.csv", GL),
    Control("Reconciliation", "Zero unexplained difference each month.",
            "Bridges A-D each show zero unexplained difference.",
            "reconciliation.md", REVENUE),
]


def control_results(checklist, integration_controls):
    """PASS/FAIL by control and month, from the checks the close already ran."""
    integration = all(passed for name, passed, _ in integration_controls
                      if name.startswith(("Every ledger row", "GL account totals", "Re-running")))
    balance = all(passed for name, passed, _ in integration_controls
                  if name.startswith(("Every journal entry", "Trial balance")))
    results = {}
    for month in MONTHS:
        c = {name: passed for name, (passed, _) in checklist[month].items()}
        results[month] = {
            "Completeness": c["Usage loaded and complete"],
            "Cutoff": c["Cutoff and lag estimate"],
            "Close threshold": c["Unusual items reviewed"],
            "Pricing accuracy": c["Invoices issued"],
            "Integration": integration,
            "Balance": balance,
            "Rollforwards": c["Rollforwards tie to the GL"],
            "Reconciliation": c["Reconciliation"],
        }
    return results


def build_controls_matrix(checklist, integration_controls):
    results = control_results(checklist, integration_controls)
    out = ["# Controls matrix", "",
           "Hedgehog Metrics, Inc. (synthetic data). Q1 2026. Generated by `python run.py`.", "",
           "Each control in SPEC section 7. All are automated, detective controls that run at every monthly "
           "close. The Controller reviews each one.", "",
           "| Control | What it proves (SPEC 7) | How the model tests it | Evidence | Owner | Reviewer | "
           + " | ".join(MONTH_NAMES[m] for m in MONTHS) + " |",
           "|---|---|---|---|---|---|" + "---|" * len(MONTHS)]
    for control in CONTROLS:
        cells = " | ".join("PASS" if results[m][control.name] else "**FAIL**" for m in MONTHS)
        out.append(f"| {control.name} | {control.proves} | {control.test} | {control.evidence} | "
                   f"{control.owner} | Controller | {cells} |")
    out.append("")
    return "\n".join(out), results


# --- Sample tie-outs ------------------------------------------------------------------------------------

SAMPLES = [
    ("INV-2026-01-TELA", "Usage invoice with a billing limit, a credit memo, and a short payment"),
    ("INV-2026-01-MOCK", "Prepaid credit invoice: contract liability, then drawdown at 0.80"),
    ("INV-2026-02-HOOD", "Usage invoice with a lag true-up line"),
    ("INV-2026-02-TELA", "Usage invoice paid 20 days late, open at March 31"),
    ("INV-2025-12-HOOD", "December invoice billed from the opening unbilled AR"),
]


def gl_lines_for(gl, ledger_ids):
    ids = set(ledger_ids)
    return gl[gl.ledger_ids.map(lambda s: bool(ids & set(s.split(";"))))]


def posting(mapping_rules, row, classification):
    key = (row.event_type, classification if row.event_type == "credit_memo" else "")
    rule = mapping_rules.get(key)
    return (rule.debit_account, rule.credit_account) if rule is not None and rule.posts == "yes" else (None, None)


def trace(invoice_id, why, *, raw_usage, usage_summary, ledger, lines, invoices, gl, mapping, adjustments, cutoff_day):
    from revrec.usage import cutoff_date

    rules = {(r.event_type, r.classification): r for r in mapping.itertuples()}
    classification = adjustments.set_index("adjustment_id")["classification"].to_dict()
    inv = invoices.set_index("invoice_id").loc[invoice_id]
    customer, month = inv.customer_id, inv.usage_month
    inv_lines = lines[lines.invoice_id == invoice_id]
    checks = []
    out = [f"## {invoice_id}: {why}", "",
           f"Customer {customer}; issued {inv.issue_date}; due {inv.due_date}; total {inv.total:,.2f}.", ""]

    # 1. Usage rows
    out += ["**1. Usage rows** (`data/usage_events.csv`)", ""]
    related_ledger = ledger[ledger.invoice_id == invoice_id]
    if month and month != "2025-12":
        cutoff = cutoff_date(month, cutoff_day).isoformat()
        rows = raw_usage[(raw_usage.customer_id == customer) & (raw_usage.received_ts.str[:7] == month)]
        dups = usage_summary.duplicates
        dups = dups[(dups.customer_id == customer) & (dups.received_ts.str[:7] == month)]
        on_time = rows[(rows.source == "normal") & (rows.processed_ts.str[:10] <= cutoff)].drop_duplicates()
        out += ["| Product | Rows | Units | First event_id | Last event_id |", "|---|---:|---:|---|---|"]
        for product, group in on_time.groupby("product", sort=True):
            out.append(f"| {product} | {len(group)} | {group.quantity.sum():,} | {group.event_id.min()} | {group.event_id.max()} |")
        out.append("")
        out.append(f"Rows received in {MONTH_NAMES[month]} (UTC) and processed by the cutoff ({cutoff}). "
                   f"{len(dups)} duplicate row(s) excluded (in exceptions.csv).")
        late = ledger[(ledger.event_type == "late_usage_rated") & (ledger.invoice_id == invoice_id)]
        for row in late.itertuples():
            out.append(f"Late usage on this invoice: {row.source_ref}, {int(row.quantity):,} units of {row.usage_month} usage.")
        out.append("")
    elif month == "2025-12":
        out += ["December 2025 usage. It's carried in from the opening unbilled AR "
                "(`data/opening_balances.csv`, `data/prior_period_invoices.csv`), not from usage rows.", ""]
    else:
        out += ["Prepaid credit: no usage rows on the invoice. Usage rows draw down the credit afterward (step 2 below).", ""]

    # 2. Billing ledger
    out += ["**2. Billing ledger** (`output/billing_ledger.csv`)", "",
            "| ledger_id | Date | Event | Product | Amount | Posts as (Dr / Cr) |", "|---|---|---|---|---:|---|"]
    if month and month != "2025-12":
        trail = ledger[((ledger.event_type == "usage_rated") & (ledger.customer_id == customer) & (ledger.usage_month == month))
                       | (ledger.invoice_id == invoice_id)]
    elif month == "2025-12":
        trail = ledger[((ledger.event_type == "opening_balance") & (ledger.customer_id == customer)) | (ledger.invoice_id == invoice_id)]
    else:
        trail = ledger[(ledger.invoice_id == invoice_id)
                       | ((ledger.customer_id == customer) & ledger.event_type.isin(["credit_drawdown", "credit_revenue_recognized"])
                          & (ledger.event_date <= "2026-03-31"))]
    for row in trail.itertuples():
        dr, cr = posting(rules, row, classification.get(row.source_ref, ""))
        posts = f"{dr} / {cr}" if dr else ("memo only" if row.event_type == "credit_drawdown" else "after period end")
        if row.event_date > "2026-03-31":
            posts = "after period end, not in Q1 GL"
        out.append(f"| {row.ledger_id} | {row.event_date} | {row.event_type} | {row.product} | {Decimal(row.amount):,.2f} | {posts} |")
    out.append("")

    # 3. Invoice
    out += ["**3. Invoice** (`output/invoices.csv`)", "",
            "| Line type | Product | Lines | Amount |", "|---|---|---:|---:|"]
    for (line_type, product), group in inv_lines.groupby(["line_type", "product"], sort=False):
        out.append(f"| {line_type} | {product} | {len(group)} | {sum(Decimal(a) for a in group.amount):,.2f} |")
    out += [f"| **Total** | | | **{inv.total:,.2f}** |", ""]

    rated = trail[trail.event_type.isin(["usage_rated", "late_usage_rated", "opening_balance"])]
    issued = trail[trail.event_type.isin(["invoice_issued", "credit_invoice_issued"])]
    if not rated.empty:
        rated_total = sum(Decimal(a) for a in rated.amount)
        checks.append(("Usage rated in the ledger equals the invoice total", rated_total == inv.total,
                       f"{rated_total:,.2f} vs {inv.total:,.2f}"))
    checks.append(("Invoice-issued ledger event equals the invoice total",
                   len(issued) == 1 and Decimal(issued.amount.iloc[0]) == inv.total, f"{issued.ledger_id.tolist()}"))

    # 4. GL
    out += ["**4. GL** (`output/gl_export.csv`)", "", "| Journal entry | Account | Debit | Credit | Includes ledger_ids |",
            "|---|---|---:|---:|---|"]
    in_period = trail[(trail.event_date <= "2026-03-31") & (trail.event_type != "credit_drawdown")]
    gl_hits = gl_lines_for(gl, in_period.ledger_id)
    for row in gl_hits.itertuples():
        out.append(f"| {row.je_id} | {row.account} {row.account_name} | {Decimal(row.debit):,.2f} | {Decimal(row.credit):,.2f} | {row.ledger_ids} |")
    out.append("")
    posted_ids = {i for s in gl_hits.ledger_ids for i in s.split(";")}
    checks.append(("Every in-period ledger event on the trail is in the GL",
                   set(in_period.ledger_id) <= posted_ids, f"{len(in_period)} events"))

    # 5. Cash
    out += ["**5. Cash** (`data/payments.csv`, GL 1000)", ""]
    paid = ledger[(ledger.event_type == "payment_applied") & (ledger.invoice_id == invoice_id)]
    memos = ledger[(ledger.event_type == "credit_memo") & (ledger.invoice_id == invoice_id)]
    memo_total = sum((Decimal(a) for a in memos.amount), ZERO)
    paid_in_q1 = sum((Decimal(a) for a in paid[paid.event_date <= "2026-03-31"].amount), ZERO)
    for row in paid.itertuples():
        when = " (after period end)" if row.event_date > "2026-03-31" else ""
        out.append(f"- {row.source_ref} received {row.event_date}{when}: {Decimal(row.amount):,.2f} ({row.ledger_id})")
    for row in memos.itertuples():
        out.append(f"- Credit memo {row.source_ref} on {row.event_date}: {Decimal(row.amount):,.2f} ({row.ledger_id})")
    open_at_q1 = inv.total - memo_total - paid_in_q1
    out += [f"- Open at March 31: {open_at_q1:,.2f}", ""]
    total_paid = sum((Decimal(a) for a in paid.amount), ZERO)
    checks.append(("Invoice total less credit memos equals cash received",
                   inv.total - memo_total == total_paid, f"{inv.total:,.2f} - {memo_total:,.2f} = {total_paid:,.2f}"))

    out += ["**Tie-out**", "", "| Check | Result | Detail |", "|---|---|---|"]
    for name, passed, detail in checks:
        out.append(f"| {name} | {'Ties' if passed else '**Does not tie**'} | {detail} |")
    out.append("")
    return out, checks, open_at_q1


def build_sample_tieouts(**kwargs):
    out = ["# Sample tie-outs", "",
           "Hedgehog Metrics, Inc. (synthetic data). Q1 2026. Generated by `python run.py`.", "",
           "Five invoices, at least one per customer, each traced from usage rows to the billing ledger, "
           "the invoice, the GL, and cash, using the `ledger_id` trail.", ""]
    all_checks = {}
    open_balances = {}
    for invoice_id, why in SAMPLES:
        section, checks, open_at_q1 = trace(invoice_id, why, **kwargs)
        out += section
        all_checks[invoice_id] = checks
        open_balances[invoice_id] = open_at_q1
    return "\n".join(out), all_checks, open_balances


def run_workpapers(output_dir, *, checklist, integration_controls, **trace_inputs):
    folder = Path(output_dir) / "workpapers"
    folder.mkdir(parents=True, exist_ok=True)
    matrix, results = build_controls_matrix(checklist, integration_controls)
    (folder / "controls_matrix.md").write_text(matrix, encoding="utf-8", newline="\n")
    tieouts, checks, open_balances = build_sample_tieouts(**trace_inputs)
    (folder / "sample_tieouts.md").write_text(tieouts, encoding="utf-8", newline="\n")
    return {"control_results": results, "tieout_checks": checks, "open_balances": open_balances}
